import { readFileSync } from "node:fs";
import { Grid } from "../web/src/shared/grid.js";
import { World } from "../web/src/shared/world.js";
import { GameData } from "../web/src/shared/data.js";
import { sset, sget, sclear } from "../web/src/shared/systems/status.js";
import { MAGIC_MODE } from "../web/src/shared/magic.js";
MAGIC_MODE.player = true;
const D = new URL("../web/data/", import.meta.url);
const meta = JSON.parse(readFileSync(new URL("map.json", D)));
const bytes = new Uint8Array(readFileSync(new URL(meta.map + ".bin", D)));
const npcDb = JSON.parse(readFileSync(new URL("npc.json", D)));
const data = new GameData({ items: JSON.parse(readFileSync(new URL("items.json", D))), magic: JSON.parse(readFileSync(new URL("magic.json", D))), npcs: npcDb });
const assert = (c, m) => { if (!c) { console.error("FALLO:", m); process.exit(1); } };
const w = new World({ grid: new Grid(meta.w, meta.h, bytes), npcDb, data, spawns: [], rng: Math.random, start: meta.start });
const aid = w.addPlayer("mago"), a = w.ents.get(aid), bid = w.addPlayer("victima"), b = w.ents.get(bid);
for (const e of [a, b]) for (const u of Object.values(e.equip)) w.command(e.id, { t: "unequip", uid: u });
a.fullMage = true; a.skills[4] = 100; a.stats.int = a.stats.mag = 200; a.level = 100; w.recalc(a);
const idOf = n => Number(Object.entries(data.magic).find(([, s]) => s.name === n)[0]);
const FB = idOf("Fire Ball"), FOOD = idOf("Create Food");
const evs = []; const _e = w.emit.bind(w); w.emit = e => { evs.push(e); return _e(e); };
const attempt = id => { a.lastCast = -1e9; a.busyUntil = 0; w.tick(1200); a.lastCast = -1e9; a.busyUntil = 0; w.command(aid, { t: "cast", spell: id, x: b.x, y: b.y }); return a.lastCast > 0; };
const tryOk = id => { for (let i = 0; i < 15; i++) if (attempt(id)) return true; return false; };
assert(tryOk(FB), "mapa normal: Fire Ball sale " + JSON.stringify(evs.filter(e => e.t === "reject").slice(-2)));
w.meta = { ...w.meta, noAttack: [[0, -10, 0, 0]] };
w.safeAt = () => false;
assert(!attempt(FB), "mapa sin ataque: Fire Ball vetado (HG.cpp:10255)");
assert(tryOk(FOOD), "mapa sin ataque: Create Food permitido (HG.cpp:10256)");
a.gm = true; assert(tryOk(FB), "GM exento (HG.cpp:10258)"); a.gm = false;
w.meta = { ...w.meta, noAttack: [], magicLimited: [FB] };
assert(!attempt(FB), "magicLimited veta el hechizo (HG.cpp:10260)");
a.gm = true; assert(tryOk(FB), "GM exento de magicLimited"); a.gm = false;
assert(tryOk(FOOD), "otro hechizo no limitado sale");
console.log("OK magic-types");
